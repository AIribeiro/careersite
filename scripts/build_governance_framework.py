from PIL import Image, ImageOps, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "images" / "54907620908_f7c872f825_o.jpg"
PDF_PATH = ROOT / "static" / "ai-data-governance-framework-a4.pdf"
