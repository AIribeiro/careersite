-- Owner-only recruiting journeys: each hiring process is distinct from its meetings.
create table if not exists public.careersite_recruiting_opportunities (
  id bigint generated by default as identity primary key,
  process_key text not null unique,
  employer text not null,
  role_title text not null,
  application_date date,
  application_evidence text not null default '',
  application_date_basis text not null default 'unknown'
    check (application_date_basis in ('unknown','confirmed_submission','candidate_reported','estimated')),
  outcome text not null default 'unknown'
    check (outcome in ('unknown','in_progress','rejected','offer','withdrawn','closed')),
  decision_date date,
  decision_evidence text not null default '',
  offer_date date,
  offer_evidence text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint recruiting_application_provenance check (
    application_date is null or length(trim(application_evidence)) > 0
  ),
  constraint recruiting_offer_provenance check (
    offer_date is null or length(trim(offer_evidence)) > 0
  ),
  constraint recruiting_decision_provenance check (
    decision_date is null or length(trim(decision_evidence)) > 0
  )
);
alter table public.careersite_recruiter_meetings
  add column if not exists opportunity_id bigint
  references public.careersite_recruiting_opportunities(id) on delete set null;
create index if not exists careersite_recruiter_meetings_opportunity_idx
  on public.careersite_recruiter_meetings (opportunity_id, scheduled_date, stage);

