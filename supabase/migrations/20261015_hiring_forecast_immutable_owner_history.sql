-- Immutable first forecast per day and model version; owner-only history.
-- No application-level PII or employer names stored. Existing October 9
-- historical snapshots in other tables are untouched.
CREATE TABLE IF NOT EXISTS public.careersite_hiring_forecast_history (
  id bigint generated by default as identity primary key,
  owner_user_id uuid not null default auth.uid(),
  forecast_day date not null,
  model_version text not null,
  central_offer_date date,
  top_offer_week date,
  top_start_week date,
  evidence_index integer check (evidence_index between 0 and 100),
  official_application_total integer,
  linked_application_processes integer,
  process_stage_counts jsonb not null default '{}'::jsonb,
  opportunity_market_effect numeric(8,5),
  opportunity_portfolio_effect numeric(8,5),
  modelled_90d numeric(7,5),
  expected_start_days jsonb not null default '{}'::jsonb,
  source_signature text not null,
  observed_at timestamptz not null default now(),
  unique(owner_user_id,forecast_day,model_version),
  constraint forecast_source_signature_nonempty check (length(source_signature) >= 16)
);
ALTER TABLE public.careersite_hiring_forecast_history ENABLE ROW LEVEL SECURITY;
