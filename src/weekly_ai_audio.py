"""Weekly AI spoken-first narration and stable MP3 URLs.

Audio is generated by GitHub Actions *once per published edition* and served
as a static MP3. Browser requests never trigger billable synthesis.
"""
from __future__ import annotations

import re
from html import escape
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIO_DIR = ROOT / "static" / "weekly-ai"
SCRIPT_OVERRIDES = ROOT / "data" / "weekly_ai_audio_scripts"
SLUG_PATTERN = re.compile(r"weekly-ai-\d{4}-\d{2}-\d{2}\Z")
INTRO = "Welcome to Weekly A I."
OUTRO = "Find links to all the original reporting in the written edition."


def valid_slug(slug: str) -> bool:
    return bool(SLUG_PATTERN.fullmatch(slug or ""))


def mp3_path(slug: str) -> Path | None:
    return AUDIO_DIR / (slug + ".mp3") if valid_slug(slug) else None


def audio_url(slug: str) -> str | None:
    path = mp3_path(slug)
    if path is None or not path.is_file() or path.stat().st_size < 1024:
        return None
    return "/weekly-ai-audio/" + slug + ".mp3"


class ParagraphReader(HTMLParser):
    """Collect paragraphs without injecting the visible publisher link label."""
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.items: list[tuple[str, bool]] = []
        self._depth = 0
        self._link = 0
        self._segments: list[str] = []
        self._linked = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "p":
            if not self._depth:
                self._segments = []
                self._linked = False
            self._depth += 1
        elif tag == "a" and self._depth:
            self._link += 1
            self._linked = True

    def handle_endtag(self, tag: str) -> None:
        if tag == "a" and self._link:
            self._link -= 1
        elif tag == "p" and self._depth:
            self._depth -= 1
            if not self._depth:
                content = re.sub(r"\s+", " ", " ".join(self._segments)).strip()
                if content:
                    self.items.append((content, self._linked))

    def handle_data(self, data: str) -> None:
        if self._depth and not self._link:
            self._segments.append(data)


def _spoken(text: str) -> str:
    """Strip screen-only headings and gently expand common acronyms."""
    text = re.sub(r"(?i)https?://\S+|www\.\S+", "", text)
    text = re.sub(r"^\s*\d{1,2}\.\s*", "", text)
    text = re.sub(r"\bAI\b", "A I", text)
    text = re.sub(r"\bUS\b", "U S", text)
    text = re.sub(r"\bHBR\b", "Harvard Business Review", text)
    text = re.sub(r"\s+", " ", text).strip(" .:–—")
    return text.rstrip(".") + "." if text else ""


def prepare_spoken_script(slug: str, html: str, *, week: int, iso_year: int) -> str:
    """Prefer editor-approved prose; otherwise derive conservative sourced narration."""
    if not valid_slug(slug):
        raise ValueError("Invalid Weekly AI slug")
    editorial = SCRIPT_OVERRIDES / (slug + ".txt")
    if editorial.is_file():
        text = editorial.read_text(encoding="utf-8").strip()
        if text:
            return text

    parser = ParagraphReader()
    parser.feed(html)
    stories = []
    signal = ""
    for paragraph, has_source in parser.items:
        if paragraph.lower().startswith("leadership signal"):
            signal = re.sub(r"(?i)^leadership signal\s*:\s*", "", paragraph).strip()
        elif has_source:
            stories.append(_spoken(paragraph))
    stories = [p for p in stories if p][:5]
    if len(stories) < 3:
        raise ValueError("Cannot narrate fewer than three credited news items")
    connectors = ("First, ", "Next, ", "Also this week, ", "Another development: ", "Finally, ")
    intro = f"{INTRO} Here's what mattered in Swedish week {week}, {iso_year}."
    segments = [intro] + [connectors[i] + s for i, s in enumerate(stories)]
    if signal:
        segments.append("The leadership signal? " + _spoken(signal))
    segments.append(OUTRO)
    return " ".join(segments)


def audio_player_html(slug: str) -> str:
    """Render only a tested existing MP3. Never display a broken audio widget."""
    url = audio_url(slug)
    if not url:
        return ""
    clean_url = escape(url, quote=True)
    return (
        '<aside class="weekly-ai-audio" id="weekly-ai-audio" data-analytics-section="weekly-ai-audio" '
        'aria-label="Audio edition">'
        '<div class="weekly-ai-audio-head"><span>LISTEN TO THIS WEEK</span>'
        '<span>Audio briefing · English</span></div>'
        '<audio controls preload="none" controlslist="nodownload" '
        'aria-label="Listen to the Weekly AI news briefing">'
        '<source src="' + clean_url + '" type="audio/mpeg">'
        'Your browser does not support audio playback.</audio>'
        '<p>Approximately one minute. The written edition below contains the original sources.</p>'
        '</aside>'
    )
