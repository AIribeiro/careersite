-- Owner-only recruiter meeting intelligence (calendar snapshot + verified evidence).
-- Deployed through Supabase migration careersite_private_recruiter_meeting_intelligence_20261019.
-- Idempotent representation in Git for later environment reconstruction.
begin;

create table if not exists public.careersite_recruiter_meetings (
  id bigint generated by default as identity primary key,
  source_kind text not null default 'manual'
    check (source_kind in ('outlook','google','evidence','manual')),
  source_event_id text,
  title text not null,
  employer text not null default '',
  role_title text not null default '',
  contact_name text not null default '',
  meeting_type text not null default 'interview'
    check (meeting_type in ('interview','recruiter_screening','hiring_manager','networking','other')),
  stage smallint check (stage between 1 and 9),
  scheduled_date date not null,
  starts_at timestamptz,
  ends_at timestamptz,
  timezone text not null default 'Europe/Stockholm',
  attendance text not null default 'unverified'
    check (attendance in ('unverified','attended','cancelled','no_show')),
  outcome text not null default 'unknown'
    check (outcome in ('unknown','next_stage','awaiting_feedback','rejected','offer','withdrawn','closed')),
  follow_up_status text not null default 'unknown'
    check (follow_up_status in ('unknown','not_needed','pending','sent')),
  follow_up_due date,
  follow_up_sent_at timestamptz,
  calendar_url text,
  evidence_note text not null default '',
  calendar_captured_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint meetings_time_order
    check (ends_at is null or starts_at is null or ends_at > starts_at)
);
create unique index if not exists careersite_recruiter_meetings_source_uidx
  on public.careersite_recruiter_meetings (source_kind,source_event_id)
  where source_event_id is not null;
create index if not exists careersite_recruiter_meetings_dates_idx
  on public.careersite_recruiter_meetings (scheduled_date desc);

alter table public.careersite_recruiter_meetings enable row level security;
revoke all on public.careersite_recruiter_meetings from public, anon, authenticated;
grant select, insert, update, delete on public.careersite_recruiter_meetings to authenticated;
grant usage, select on sequence public.careersite_recruiter_meetings_id_seq to authenticated;

do $$
declare
  owner_rule text := $rule$
    (select auth.uid()) is not null
    and lower(coalesce((select auth.jwt())->>'email','')) = 'jair.ribeiro@outlook.it'
    and coalesce((select auth.jwt())->>'is_anonymous','false') = 'false'
  $rule$;
begin
  if not exists (
    select 1 from pg_policies where schemaname='public'
      and tablename='careersite_recruiter_meetings' and policyname='Owner reads recruiter meetings'
  ) then
    execute format(
      'create policy %I on public.careersite_recruiter_meetings for select to authenticated using (%s)',
      'Owner reads recruiter meetings', owner_rule
    );
  end if;
  if not exists (
    select 1 from pg_policies where schemaname='public'
      and tablename='careersite_recruiter_meetings' and policyname='Owner inserts recruiter meetings'
  ) then
    execute format(
      'create policy %I on public.careersite_recruiter_meetings for insert to authenticated with check (%s)',
      'Owner inserts recruiter meetings', owner_rule
    );
  end if;
  if not exists (
    select 1 from pg_policies where schemaname='public'
      and tablename='careersite_recruiter_meetings' and policyname='Owner updates recruiter meetings'
  ) then
    execute format(
      'create policy %I on public.careersite_recruiter_meetings for update to authenticated using (%s) with check (%s)',
      'Owner updates recruiter meetings', owner_rule, owner_rule
    );
  end if;
  if not exists (
    select 1 from pg_policies where schemaname='public'
      and tablename='careersite_recruiter_meetings' and policyname='Owner deletes recruiter meetings'
  ) then
    execute format(
      'create policy %I on public.careersite_recruiter_meetings for delete to authenticated using (%s)',
      'Owner deletes recruiter meetings', owner_rule
    );
  end if;
end $$;

comment on table public.careersite_recruiter_meetings is
  'Private owner-only recruiter meeting ledger. Calendar evidence is a point-in-time snapshot, not a live sync. Past scheduled dates do not prove attendance.';

commit;
