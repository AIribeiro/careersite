NAVY=(6,29,46); MID=(12,50,72); CARD=(12,45,65)
EDGE=(47,104,128); CYAN=(103,224,240); PALE=(218,242,249)
WHITE=(249,253,255); MUTED=(181,211,222)

def portrait(source: Path, destination: Path, size: int=320) -> None:
    with Image.open(source) as raw:
        image=raw.convert("RGB")
        w,h=image.size
        # Source photo depicts Jair speaking at a public leadership event.
        x1,y1,x2,y2=[int(v) for v in (w*.37,h*.12,w*.69,h*.60)]
        extent=min(x2-x1,y2-y1)
        center=((x1+x2)//2,(y1+y2)//2)
        crop=(center[0]-extent//2,center[1]-extent//2,
              center[0]+extent//2,center[1]+extent//2)
        result=ImageOps.fit(image.crop(crop),(size,size),Image.Resampling.LANCZOS)
        alpha=Image.new("L",(size,size))
        ImageDraw.Draw(alpha).ellipse((2,2,size-3,size-3),fill=255)
        result=result.convert("RGBA");result.putalpha(alpha)
        destination.parent.mkdir(parents=True,exist_ok=True)
        if destination.suffix==".webp":
            result.save(destination,"WEBP",quality=84,method=6)
        else:
            result.save(destination,"PNG",optimize=True)

class Diagram(FPDF):
    def box(self,x,y,w,h,fill=CARD,border=EDGE,r=2.1):
        self.set_fill_color(*fill);self.set_draw_color(*border)
        self.set_line_width(.19)
        self.rect(x,y,w,h,style="DF",round_corners=True,corner_radius=r)
    def txt(self,x,y,t,sz=7,col=WHITE,bold=False):
        self.set_font("Dv","B" if bold else "",sz)
        self.set_text_color(*col);self.set_xy(x,y)
        self.cell(0,sz*.41,text=t)
    def caption(self,x,y,w,t,size=7,color=MUTED,lead=3.4):
        self.set_font("Dv","",size);self.set_text_color(*color)
        self.set_xy(x,y);self.multi_cell(w,lead,text=t)
    def rule(self,x1,y,x2,color=EDGE):
        self.set_draw_color(*color);self.set_line_width(.18);self.line(x1,y,x2,y)
    def section(self,x,y,n,title):
        self.txt(x,y,n,6.6,CYAN,True)
        self.txt(x+11,y,title,7.3,WHITE,True)
        self.rule(x,y+5,x+40)

